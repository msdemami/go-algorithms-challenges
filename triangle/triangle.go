package triangle

// ۱. تعریف نوع داده‌ی اختصاصی برای نوع مثلث (از جنس عدد صحیح)
type Kind int

// ۲. اعلان ثابت‌ها با استفاده از iota (شمارنده‌ی خودکار)
const (
    NaT Kind = iota // 0: Not a triangle (اصلاً مثلث نیست)
    Equ             // 1: Equilateral (متساوی‌الاضلاع)
    Iso             // 2: Isosceles (متساوی‌الساقین)
    Sca             // 3: Scalene (مختلف‌الاضلاع)
)

// KindFromSides تشخیص می‌دهد که این سه ضلع چه مثلثی می‌سازند
func KindFromSides(a, b, c float64) Kind {
    // شرط اول: آیا اصلاً این یک مثلث معتبر است؟
    // طول همه‌ی ضلع‌ها باید بزرگ‌تر از ۰ باشد و مجموع هر دو ضلع بزرگ‌تر یا مساوی ضلع سوم
    isTriangle := a > 0 && b > 0 && c > 0 && a+b >= c && a+c >= b && b+c >= a
    
    // اگر مثلث نبود، بلافاصله NaT را برمی‌گردانیم
    if !isTriangle {
        return NaT
    }

    // شرط دوم: متساوی‌الاضلاع (هر سه ضلع کاملاً برابر باشند)
    if a == b && b == c {
        return Equ
    }

    // شرط سوم: متساوی‌الساقین (حداقل دو ضلع با هم برابر باشند)
    if a == b || a == c || b == c {
        return Iso
    }

    // شرط چهارم: مختلف‌الاضلاع (هیچ ضلعی با دیگری برابر نیست)
    return Sca
}